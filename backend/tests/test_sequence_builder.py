"""
Golden tests on 12 real EURO 2020 goal sequences (tests/fixtures/golden_sequences.json,
regenerated by scripts/make_golden.py).

- Normalisation invariant: defenders sit nearer their own goal (x=0) than attackers.
- Collapse snapshot: re-running detect_collapse on the stored frames lands on the
  stored frame, and GOLDEN_COLLAPSE pins those frames so any change to the
  detection rule shows up here as an explicit, reviewed diff.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.models.frame import GoalSequenceResponse
from app.services import collapse
from app.services.sequence_builder import parse_timestamp

FIXTURE = Path(__file__).parent / "fixtures" / "golden_sequences.json"

# goal_event_id prefix -> collapse_frame_index. Update deliberately when the rule changes.
GOLDEN_COLLAPSE: dict[str, int | None] = {
    "51e7dde0": 7,
    "492b2a06": 1,
    "6605af47": 7,
    "a221a567": 4,
    "9edcdce4": 3,
    "9dd74d3f": None,
    "61f2991a": None,
    "3440b2d2": 9,
    "35f6e898": None,
    "3b50aa84": None,
    "ccf0702d": 17,
    "99f94455": 1,
}


def _load() -> list[GoalSequenceResponse]:
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    return [GoalSequenceResponse.model_validate(s) for s in data["sequences"]]


SEQUENCES = _load()


def _id(seq: GoalSequenceResponse) -> str:
    return seq.goal_event_id[:8]


def test_fixture_covers_every_snapshot_goal():
    assert sorted(_id(s) for s in SEQUENCES) == sorted(GOLDEN_COLLAPSE)


@pytest.mark.parametrize("seq", SEQUENCES, ids=_id)
def test_keepers_on_their_own_side_every_frame(seq: GoalSequenceResponse):
    """The mirror check: the defended goal is always at x=0, so the defending
    keeper is in the left half and the attacking keeper in the right half."""
    for f in seq.frames:
        for p in f.players:
            if not p.keeper:
                continue
            left_half = p.x < 60
            assert left_half != p.is_attacker, (
                f"frame {f.frame_index} ({f.event_type}): "
                f"{'attacking' if p.is_attacker else 'defending'} keeper at x={p.x}"
            )


# Defenders' mean x is below attackers' in most frames, but not all: inside the box
# attackers legitimately sit deeper than the defenders' average (31 of 111 golden
# frames, all within 4 units except two frames showing only 2-4 defenders).
MAX_INVERSION = 15.0
MIN_SHARE_ORDERED = 0.6


def _mean_x(f, attackers: bool) -> float | None:
    xs = [p.x for p in f.players if p.is_attacker == attackers and not p.keeper]
    return sum(xs) / len(xs) if xs else None


def test_defenders_mostly_deeper_than_attackers():
    ordered = total = 0
    for seq in SEQUENCES:
        for f in seq.frames:
            d, a = _mean_x(f, False), _mean_x(f, True)
            if d is None or a is None:
                continue
            total += 1
            ordered += d < a
            assert d - a < MAX_INVERSION, (
                f"{_id(seq)} frame {f.frame_index}: def mean {d:.1f} vs att mean {a:.1f}"
            )
    assert ordered / total >= MIN_SHARE_ORDERED


@pytest.mark.parametrize("seq", SEQUENCES, ids=_id)
def test_collapse_snapshot(seq: GoalSequenceResponse):
    stored_flags = [f.is_collapse_frame for f in seq.frames]
    stored_deltas = [f.score_delta for f in seq.frames]

    collapse.detect_collapse(seq.frames)

    assert collapse.collapse_frame_index(seq.frames) == GOLDEN_COLLAPSE[_id(seq)]
    assert seq.collapse_frame_index == GOLDEN_COLLAPSE[_id(seq)]
    assert [f.is_collapse_frame for f in seq.frames] == stored_flags
    assert [f.score_delta for f in seq.frames] == stored_deltas


@pytest.mark.parametrize("seq", SEQUENCES, ids=_id)
def test_frames_are_indexed_and_ordered(seq: GoalSequenceResponse):
    assert [f.frame_index for f in seq.frames] == list(range(len(seq.frames)))
    keys = [(f.period, f.timestamp_seconds) for f in seq.frames]
    assert keys == sorted(keys)


@pytest.mark.parametrize(
    "ts, expected",
    [("00:01:02.500", 62.5), ("01:00:00.000", 3600.0), ("garbage", 0.0)],
)
def test_parse_timestamp(ts: str, expected: float):
    assert parse_timestamp(ts) == expected
